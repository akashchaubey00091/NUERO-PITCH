/**
 * Generates dynamic 60-frame tracking sequence with realistic pitch coordinates
 */
export function generateSampleTrackingFrames(players: Player[]): TrackingFrame[] {
  const frames: TrackingFrame[] = [];
  const totalFrames = 60;

  for (let f = 0; f < totalFrames; f++) {
    const t = f / totalFrames; // 0 to 1
    const timestamp = f * 0.5; // 0 to 30 seconds

    // Ball motion: build-up pass from Ederson -> Stones -> Rodri -> De Bruyne -> Haaland shot
    let ballX = 12 + t * 70 + Math.sin(t * Math.PI * 4) * 8;
    let ballY = 34 + Math.sin(t * Math.PI * 3) * 16;
    let ballZ = Math.max(0, Math.sin(t * Math.PI * 6) * 1.8);

    const framePlayers = players.map((p) => {
      // Base position plus realistic continuous kinematic motion
      const isHome = p.teamId === 'home';
      const forwardShift = isHome ? t * 14 : -t * 10;
      const lateralShift = Math.sin(t * Math.PI * 2 + p.number) * 4.5;

      const currentX = Math.max(2, Math.min(103, p.currentX + forwardShift + Math.cos(t * 3 + p.number) * 2));
      const currentY = Math.max(2, Math.min(66, p.currentY + lateralShift));

      const vx = Number(((forwardShift / 0.5) * 0.1).toFixed(2));
      const vy = Number(((lateralShift / 0.5) * 0.1).toFixed(2));
      const instantaneousSpeed = Number(Math.max(2.5, Math.hypot(vx, vy) * 3.6 + (p.metrics.topSpeedKmh > 33 ? 12 : 6)).toFixed(1));

      // Bounding box in normalized camera space (0..1)
      const normX = currentX / 105;
      const normY = currentY / 68;
      const cameraPerspective = 1 - normY * 0.35;
      const cx = 0.5 + (normX - 0.5) * cameraPerspective;
      const cy = 0.28 + normY * 0.62;
      const boxW = 0.024 * (1.2 - normY * 0.4);
      const boxH = 0.055 * (1.2 - normY * 0.4);

      return {
        id: p.id,
        teamId: p.teamId,
        number: p.number,
        x: Number(currentX.toFixed(2)),
        y: Number(currentY.toFixed(2)),
        vx,
        vy,
        speed: instantaneousSpeed,
        confidence: Number((0.82 + Math.sin(f * 0.2 + p.number) * 0.08).toFixed(2)),
        bbox: [
          Math.max(0.01, cx - boxW / 2),
          Math.max(0.01, cy - boxH),
          boxW,
          boxH,
        ] as [number, number, number, number],
      };
    });

    const homeP = framePlayers.filter((p) => p.teamId === 'home');
    const awayP = framePlayers.filter((p) => p.teamId === 'away');

    const homeCentroid = {
      x: Number((homeP.reduce((s, p) => s + p.x, 0) / homeP.length).toFixed(1)),
      y: Number((homeP.reduce((s, p) => s + p.y, 0) / homeP.length).toFixed(1)),
    };

    const awayCentroid = {
      x: Number((awayP.reduce((s, p) => s + p.x, 0) / awayP.length).toFixed(1)),
      y: Number((awayP.reduce((s, p) => s + p.y, 0) / awayP.length).toFixed(1)),
    };

    let tacticalPhase = 'Constructive Build-Up';
    if (f > 15 && f <= 32) tacticalPhase = 'Midfield Penetration';
    if (f > 32 && f <= 48) tacticalPhase = 'Final Third Overload';
    if (f > 48) tacticalPhase = 'Box Entry & Shot Generation';

    frames.push({
      frameIndex: f,
      timestampSeconds: Number(timestamp.toFixed(1)),
      ball: {
        x: Number(ballX.toFixed(2)),
        y: Number(ballY.toFixed(2)),
        z: Number(ballZ.toFixed(2)),
        speedKmh: Number((24 + Math.sin(t * 8) * 18).toFixed(1)),
      },
      players: framePlayers,
      tacticalPhase,
      possessionTeamId: 'home',
      homeCentroid,
      awayCentroid,
    });
  }

  return frames;
}

